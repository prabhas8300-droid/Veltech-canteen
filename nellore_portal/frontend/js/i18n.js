let currentLang = 'en';

function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('nellore_lang', lang);
    
    // Update active state in UI
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('bg-amber-500', 'text-slate-900', 'font-bold');
            btn.classList.remove('text-white', 'hover:bg-slate-700');
        } else {
            btn.classList.remove('bg-amber-500', 'text-slate-900', 'font-bold');
            btn.classList.add('text-white', 'hover:bg-slate-700');
        }
    });

    // Update text elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });

    // Update placeholders with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang][key]) {
            el.setAttribute('placeholder', translations[lang][key]);
        }
    });
}

// Initializer
document.addEventListener('DOMContentLoaded', () => {
    const saved = localStorage.getItem('nellore_lang') || 'en';
    setLanguage(saved);
});
